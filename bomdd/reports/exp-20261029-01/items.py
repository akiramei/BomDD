"""List the derived-layer decisions of MoviePad-Remake at a fixed commit (EXP-20261029-01).

Reads 32-mbom.yaml, 33-control-plan.yaml and 34-routing.yaml from the commit with `git show`, so the
working tree does not matter. Writes items.json and items.md next to this file: one item per decision
the orchestrating AI wrote (definitions.md section 2), with the text it wrote and no class.

usage: python items.py <path to MoviePad-Remake> [commit]
"""
import json
import os
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))


def show(repo, commit, path):
    out = subprocess.run(['git', '-C', repo, 'show', f'{commit}:{path}'], check=True,
                         capture_output=True).stdout
    return yaml.safe_load(out.decode('utf-8'))


def text(v):
    if v is None:
        return ''
    if isinstance(v, str):
        return ' '.join(v.split())
    return json.dumps(v, ensure_ascii=False)


def main():
    repo = sys.argv[1]
    commit = sys.argv[2] if len(sys.argv) > 2 else 'd3683d6'
    mbom = show(repo, commit, 'bomdd/32-mbom.yaml')['mbom']
    cp = show(repo, commit, 'bomdd/33-control-plan.yaml')['control_plan']
    rt = show(repo, commit, 'bomdd/34-routing.yaml')['routing']
    items = []

    def add(iid, kind, where, value):
        items.append({'id': iid, 'kind': kind, 'where': where, 'value': value})

    for u in mbom['manufacturing_units']:
        uid = u['id']
        add(f'UNIT/{uid}', 'unit-partition', f'32-mbom.yaml {uid}',
            text({'ebom_refs': u.get('ebom_refs'), 'artifact': u.get('artifact'),
                  'planned_output_artifact_ref': u.get('planned_output_artifact_ref')}))
        reqs = (u.get('part_standard') or {}).get('requires') or []
        add(f'DEP/{uid}', 'dependencies', f'32-mbom.yaml {uid}',
            text({'depends_on': u.get('depends_on'), 'requires': reqs}))
        add(f'ACC/{uid}', 'acceptance-refs', f'32-mbom.yaml {uid}', text(u.get('acceptance_refs')))
        for p in (u.get('part_standard') or {}).get('provides') or []:
            body = p.get('form') if p.get('form') is not None else p.get('statement')
            add(f'PROVIDES/{p["id"]}', f'provides-{p.get("kind")}', f'32-mbom.yaml {uid}',
                text({'ruled_ref': p.get('ruled_ref'), 'text': text(body)}))
        for n, d in enumerate(u.get('manufacturing_decisions') or [], 1):
            add(f'MD/{uid}/{n}', 'manufacturing-decision', f'32-mbom.yaml {uid}', text(d))
    add('ASSEMBLY', 'assembly-refs', '32-mbom.yaml mbom.assembly', text(mbom.get('assembly')))

    for r in cp['characteristics']:
        rid = r['id']
        add(f'CPROW/{rid}', 'cp-row-partition', f'33-control-plan.yaml {rid}',
            text({'characteristic': r.get('characteristic'), 'requirement_refs': r.get('requirement_refs')}))
        add(f'CPLINK/{rid}', 'cp-links', f'33-control-plan.yaml {rid}',
            text({k: r.get(k) for k in ('verifies', 'part_standard_refs', 'invariant_refs')}))
        add(f'CPMETHOD/{rid}', 'cp-method', f'33-control-plan.yaml {rid}',
            text({k: r.get(k) for k in ('depth', 'tolerance', 'fixture', 'oracle', 'test_vectors', 'known_limits')}))
        add(f'CPPOLICY/{rid}', 'cp-policy', f'33-control-plan.yaml {rid}',
            text({k: r.get(k) for k in ('classification', 'when', 'on_fail', 'approver')}))

    for s in rt['steps']:
        add(f'ROUTE/{s["id"]}', 'routing-step', f'34-routing.yaml {s["id"]}',
            text({k: v for k, v in s.items() if k not in ('id',)}))

    with open(os.path.join(HERE, 'items.json'), 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'repo': 'MoviePad-Remake', 'commit': commit, 'items': items}, f, ensure_ascii=False, indent=1)
        f.write('\n')
    with open(os.path.join(HERE, 'items.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# Derived-layer items of MoviePad-Remake at {commit} (generated by items.py; no class)\n\n')
        for it in items:
            f.write(f'- **{it["id"]}** ({it["kind"]}; {it["where"]}): {it["value"]}\n')
    kinds = {}
    for it in items:
        kinds[it['kind']] = kinds.get(it['kind'], 0) + 1
    print(len(items), 'items', json.dumps(kinds))


if __name__ == '__main__':
    main()
