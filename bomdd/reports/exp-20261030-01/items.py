"""EXP-20261030-01 - list the candidate upstream defects (definitions.md section 2).

Reads each product's change register at a pinned commit (git show, not the working tree) and writes
items.json and items.md next to this file. Selection is mechanical; screening (IN/OUT) is the classifiers'.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPOS = HERE.parents[3]  # .../source/repos

PINS = {
    "ViewTube": "62d2b3e432de4cbc8263cbc5a77804f057a114ed",
    "ViewPrism2": "82c362edafcfbb09591da7bb937beffeb01a2fcd",
    "MoviePad-Remake": "a2ca41ec49d7c688d9a3685c0deabec4d996c1d9",
}
MP_G2_COMMIT = "22e2213"  # MoviePad-Remake: the spec at G2's cut-off adoption

# ViewPrism2's register has no layer field; its free-text `type` is matched (definitions.md 2.2).
VP2_UPSTREAM = re.compile(r"spec|仕様|CAD|要求|要件|E-BOM|K-BOM|沈黙|未定義|曖昧|欠落|欠測|omission|脱漏|不整合")
VP2_EXCLUDE = re.compile(r"^(機能拡張|新機能|新規|既存機能拡張|工程|検査器|台帳|process)")


def show(product, path, rev=None):
    rev = rev or PINS[product]
    out = subprocess.run(["git", "-C", str(REPOS / product), "show", f"{rev}:{path}"],
                         capture_output=True, check=True)
    return out.stdout.decode("utf-8")


def entries(doc):
    if isinstance(doc, dict):
        if "changes" in doc:
            return doc["changes"]
        return next(v for v in doc.values() if isinstance(v, list))
    return doc


def viewtube():
    reg = entries(yaml.safe_load(show("ViewTube", "bomdd/process/change-register.yaml")))
    for e in reg:
        layer = str(e.get("diagnosis_layer", "")).strip("'")
        if layer in ("ui_cad", "requirements_bom_control") and e.get("status") in ("applied", "implemented"):
            yield {"source": e["id"], "title": e.get("title", ""), "label": f"diagnosis_layer={layer}; "
                   f"change_class={str(e.get('change_class', '')).strip()[:200]}",
                   "status": e.get("status"), "order": f"ViewTube/{e.get('body')}"}


def viewprism2():
    reg = entries(yaml.safe_load(show("ViewPrism2", "bomdd/60-change-register.yaml")))
    for e in reg:
        t = str(e.get("type", "")).strip().strip('"')
        if VP2_UPSTREAM.search(t) and not VP2_EXCLUDE.search(t):
            yield {"source": e["id"], "title": e.get("title", ""), "label": f"type={t}",
                   "status": e.get("status"), "order": f"ViewPrism2/{e.get('body')}"}


def moviepad():
    reg = entries(yaml.safe_load(show("MoviePad-Remake", "bomdd/60-change-register.yaml")))
    for e in reg:
        yield {"source": e["id"], "title": e.get("title", ""), "label": "change register entry (all six listed)",
               "status": e.get("status"), "order": f"MoviePad-Remake/{e.get('order_ref')}"}
    spec = show("MoviePad-Remake", "bomdd/20-spec.md", MP_G2_COMMIT)
    # a round's list wraps onto lines indented by four spaces
    for m in re.finditer(r"^  - Round (\d): (.+?)\.\n(?!    )", spec, re.M | re.S):
        for k, topic in enumerate(t.strip() for t in re.sub(r"\s+", " ", m.group(2)).split(", ")):
            yield {"source": f"G2-R{m.group(1)}-{k + 1}", "title": topic,
                   "label": "G2 audit finding topic (a heading only; the finding's text is not kept in the repository)",
                   "status": "applied in the spec", "order": f"MoviePad-Remake/bomdd/20-spec.md@{MP_G2_COMMIT} (Gate record)"}


def main():
    items = []
    for product, prefix, gen in (("ViewTube", "VT", viewtube), ("ViewPrism2", "VP", viewprism2),
                                 ("MoviePad-Remake", "MP", moviepad)):
        for n, it in enumerate(gen(), 1):
            items.append({"id": f"{prefix}-{n:03d}", "product": product, **it})
    meta = {"pins": PINS, "moviepad_g2_commit": MP_G2_COMMIT, "count": len(items),
            "per_product": {p: sum(i["product"] == p for i in items) for p in PINS}}
    (HERE / "items.json").write_text(json.dumps({"meta": meta, "items": items}, ensure_ascii=False, indent=1) + "\n",
                                     encoding="utf-8", newline="\n")
    lines = ["# EXP-20261030-01 — items (generated by items.py; do not edit)", "",
             f"Pins: {json.dumps(PINS)}; MoviePad-Remake G2 topics from `{MP_G2_COMMIT}`. Count {len(items)}: "
             + ", ".join(f"{p} {c}" for p, c in meta["per_product"].items()) + ".", "",
             "| id | source | status | title | label | order |", "|---|---|---|---|---|---|"]
    for i in items:
        cells = [i["id"], i["source"], str(i["status"]), i["title"], i["label"], i["order"]]
        lines.append("| " + " | ".join(c.replace("|", "/").replace("\n", " ") for c in cells) + " |")
    (HERE / "items.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    sys.stdout.write(json.dumps(meta) + "\n")


if __name__ == "__main__":
    main()
